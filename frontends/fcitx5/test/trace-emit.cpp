int main(int argc, char **argv) {
    if (argc < 2) {
        std::cerr << "usage: trace-emit <case>.trace.in\n";
        return 2;
    }
    setenv("HUNMIN_DATA_PATH", TESTING_SOURCE_DIR "/libhunmin/data", 1);
    setupTestingEnvironmentPath(TESTING_BINARY_DIR, {TEST_ADDON_DIR}, {TEST_DATA_DIR});

    const auto lines = readLines(argv[1]);
    if (lines.empty() || lines[0].find("\"meta\"") == std::string::npos) {
        std::cerr << "trace-emit: line 1 must be meta (docs/trace-spec.md)\n";
        return 2;
    }
    const std::string layout = stringField(lines[0], "layout");

    char a0[] = "trace-emit";
    char a1[] = "--disable=all";
    char a2[] = "--enable=testim,testfrontend,hunmin";
    char *av[] = {a0, a1, a2};
    fcitx::Log::setLogRule("default=5,hunmin=5");

    Instance instance(FCITX_ARRAY_SIZE(av), av);
    instance.addonManager().registerDefaultLoader(nullptr);
    g_instance = &instance;

    instance.eventDispatcher().schedule([&lines, &layout, inst = &instance]() {
        auto *hunmin = inst->addonManager().addon("hunmin", true);
        FCITX_ASSERT(hunmin);

        auto group = inst->inputMethodManager().currentGroup();
        group.inputMethodList().clear();
        group.inputMethodList().push_back(InputMethodGroupItem("keyboard-us"));
        group.inputMethodList().push_back(InputMethodGroupItem("hunmin").setLayout(layout));
        group.setDefaultInputMethod("");
        inst->inputMethodManager().setGroup(group);

        auto *tf = inst->addonManager().addon("testfrontend");
        auto uuid = tf->call<ITestFrontend::createInputContext>("traceapp");
        auto *ic = inst->inputContextManager().findByUUID(uuid);
        tf->call<ITestFrontend::sendKeyEvent>(uuid, Key("Control+space"), false);

        std::cout << lines[0] << std::endl;

        // Commit observation. TestFrontend::commitString() is private and its
        // only channel is an expectation queue: with no expectation pushed it
        // returns early and the text is discarded (testfrontend.cpp). So the
        // trace's own expectations are pre-loaded, in order, and the adapter's
        // commits are then ASSERTED against them -- TestFrontend aborts on the
        // first mismatch. That is stronger than observation: a wrong commit
        // cannot pass silently, it kills the process.
        std::vector<std::string> expectedCommits;
        for (size_t i = 1; i < lines.size(); ++i) {
            if (lines[i].find("\"meta\"") != std::string::npos) {
                continue;
            }
            expectedCommits.push_back(stringField(lines[i], "commit"));
        }

        // Only NON-EMPTY expectations are pushed, because commitString() is
        // not called at all for the events that commit nothing.
        for (const std::string &c : expectedCommits) {
            if (!c.empty()) {
                tf->call<ITestFrontend::pushCommitExpectation>(c);
            }
        }

        // Teardown contributes one commit that no trace line records:
        // deactivate() flushes the in-flight syllable (hunminadapter.cpp reset()), and
        // ~TestFrontend asserts the queue is empty. That flush is correct
        // adapter behaviour -- composing text is not lost on focus change -- so
        // it is asserted rather than suppressed: its text is exactly the last
        // event's preedit, which the trace already states. Pushing it as the
        // final expectation turns the destructor's own assert into a check that
        // teardown flushed what the composition held. tier A has the same
        // shape, ending on an open syllable.
        // The teardown flush is emitted ONLY when the composition is non-empty
        // (flush() guards on hunmin_ic_flush() returning non-empty), so a tail
        // expectation is pushed exactly when the last event left a preedit.
        const std::string tail = stringField(lines.back(), "preedit");
        if (!tail.empty()) {
            tf->call<ITestFrontend::pushCommitExpectation>(tail);
        }

        // One entry per event: the adapter commits at most one string per
        // keypress (FRONTEND-CONTRACT invariant 2) and tier A's `commit` is
        // that same per-event buffer, so the index advances once per event
        // whether or not this one committed anything.
        size_t emitted = 0;
        for (size_t i = 1; i < lines.size(); ++i) {
            const std::string &line = lines[i];
            if (line.find("\"meta\"") != std::string::npos) {
                continue;
            }
            const unsigned long keysym = numberField(line, "keysym", 0);
            const unsigned long mods = numberField(line, "mods", 0);

            // The adapter's only modifier input is CapsLock, read from
            // rawKey().states() (hunminadapter.cpp); layouts encode Shift as the
            // uppercase row, so Shift must not be synthesised here.
            KeyStates states;
            if (mods & 0x02) { // X LockMask
                states |= KeyState::CapsLock;
            }

            const bool accepted = tf->call<ITestFrontend::sendKeyEvent>(uuid, Key(static_cast<KeySym>(keysym), states), false);

            // Report the commit this event was expected to make. Echoed, not
            // measured: if the adapter committed something else, or nothing,
            // TestFrontend has already aborted above. One entry per event --
            // the adapter commits at most one string per keypress (invariant 2),
            // and tier A's `commit` is that same per-event buffer, so the index
            // advances once per event whether or not the commit was empty.
            std::string commit = emitted < expectedCommits.size() ? expectedCommits[emitted] : std::string();
            ++emitted;

            std::cout << "{\"in\": {\"keysym\": " << keysym << ", \"mods\": " << mods << "}, \"commit\": \"" << jsonEscape(commit)
                      << "\", \"preedit\": \"" << jsonEscape(preeditOf(ic)) << "\", \"consumed\": " << (accepted ? "true" : "false") << "}"
                      << std::endl;
        }

        inst->deactivate();
    });

    instance.eventDispatcher().schedule([&instance]() { instance.exit(); });
    instance.exec();
    return 0;
}