// JSON string escaping for the values this corpus carries: NFC Hangul, Hanja
// and ASCII. Control characters beyond the standard escapes do not occur, but
// they are handled rather than emitted raw so a malformed corpus cannot inject
// broken JSON into the runner's output.
std::string jsonEscape(const std::string &s) {
    std::string o;
    for (char c : s) {
        switch (c) {
        case '"':
            o += "\\\"";
            break;
        case '\\':
            o += "\\\\";
            break;
        case '\n':
            o += "\\n";
            break;
        case '\r':
            o += "\\r";
            break;
        case '\t':
            o += "\\t";
            break;
        default:
            if (static_cast<unsigned char>(c) < 0x20) {
                char buf[8];
                std::snprintf(buf, sizeof buf, "\\u%04x", static_cast<unsigned>(static_cast<unsigned char>(c)));
                o += buf;
            } else {
                o += c;
            }
        }
    }
    return o;
}

// Minimal reader for the exact shape docs/trace-spec.md defines. Not a general
// JSON parser on purpose: the corpus is machine-generated by
// tools/gen-conformance.py, and tier C should not need a JSON dependency to read
// six fields. Anything outside the shape is rejected by tools/trace-check.py,
// which owns the spec.
std::vector<std::string> readLines(const std::string &path) {
    std::ifstream f(path);
    if (!f) {
        std::cerr << "trace-emit: cannot open " << path << "\n";
        std::exit(2);
    }
    std::vector<std::string> out;
    std::string l;
    while (std::getline(f, l)) {
        if (!l.empty()) {
            out.push_back(l);
        }
    }
    return out;
}

unsigned long numberField(const std::string &line, const char *key, unsigned long fallback) {
    const std::string pat = std::string("\"") + key + "\"";
    auto p = line.find(pat);
    if (p == std::string::npos) {
        return fallback;
    }
    p = line.find(':', p + pat.size());
    if (p == std::string::npos) {
        return fallback;
    }
    ++p;
    while (p < line.size() && std::isspace(static_cast<unsigned char>(line[p]))) {
        ++p;
    }
    if (p < line.size() && line[p] == '"') {
        return fallback;
    }
    return std::strtoul(line.c_str() + p, nullptr, 0);
}

std::string stringField(const std::string &line, const char *key) {
    const std::string pat = std::string("\"") + key + "\"";
    auto p = line.find(pat);
    if (p == std::string::npos) {
        return {};
    }
    p = line.find(':', p + pat.size());
    if (p == std::string::npos) {
        return {};
    }
    ++p;
    while (p < line.size() && std::isspace(static_cast<unsigned char>(line[p]))) {
        ++p;
    }
    if (p >= line.size() || line[p] != '"') {
        return {};
    }
    ++p;
    std::string o;
    while (p < line.size() && line[p] != '"') {
        if (line[p] == '\\' && p + 1 < line.size()) {
            switch (line[++p]) {
            case 'n':
                o += '\n';
                break;
            case 't':
                o += '\t';
                break;
            case 'r':
                o += '\r';
                break;
            case 'u': {
                const unsigned cp = std::strtoul(line.c_str() + p + 1, nullptr, 16);
                if (cp < 0x80) {
                    o += static_cast<char>(cp);
                } else if (cp < 0x800) {
                    o += static_cast<char>(0xC0 | (cp >> 6));
                    o += static_cast<char>(0x80 | (cp & 0x3F));
                } else {
                    o += static_cast<char>(0xE0 | (cp >> 12));
                    o += static_cast<char>(0x80 | ((cp >> 6) & 0x3F));
                    o += static_cast<char>(0x80 | (cp & 0x3F));
                }
                p += 4;
                break;
            }
            default:
                o += line[p];
            }
            ++p;
            continue;
        }
        o += line[p++];
    }
    return o;
}

// The adapter picks one of two accessors depending on the context's capability
// (hunminadapter.cpp updateUI()); tier C must observe whichever one it used, exactly as
// a client would. Both are read so the trace does not depend on the branch.
std::string preeditOf(InputContext *ic) {
    if (ic->capabilityFlags().test(CapabilityFlag::Preedit)) {
        return ic->inputPanel().clientPreedit().toString();
    }
    return ic->inputPanel().preedit().toString();
}

