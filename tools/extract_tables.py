#!/usr/bin/env python3
"""Generate libhunmin/src/tables.c + tables.h from vendored libhangul source.

The pure jamo tables/predicates in libhangul's hangulctype.c are data facts of
the Unicode Hangul blocks; we extract them verbatim (renamed hm_*) so parity
with the reference engine is mechanical, not transcribed. libhangul is
LGPL-2.1+; hunmin's core is LGPL-2.1+ -> license-compatible derivation.
Regenerate after updating data-orig:  python3 tools/extract_tables.py
"""
import re
import sys
from pathlib import Path
try:  # issue #272 phase 2: one ROOT derivation, with a file-relative fallback
    from _common import ROOT as _COMMON_ROOT
except ImportError:  # run from outside tools/: derive from this file
    _COMMON_ROOT = __import__("pathlib").Path(__file__).resolve().parent.parent

SRC = _COMMON_ROOT / "data-orig/libhangul/hangulctype.c"
OUT = _COMMON_ROOT / "libhunmin/src"

FUNCS = [
    "hangul_is_choseong", "hangul_is_jungseong", "hangul_is_jongseong",
    "hangul_is_jamo", "hangul_is_cjamo",
    "hangul_is_choseong_conjoinable", "hangul_is_jungseong_conjoinable",
    "hangul_is_jongseong_conjoinable", "hangul_is_jamo_conjoinable",
    "hangul_jongseong_get_ncomponent", "hangul_choseong_to_jongseong",
    "hangul_jongseong_to_choseong", "hangul_jongseong_get_diff",
    "hangul_jamo_to_cjamo", "hangul_jongseong_decompose",
    "hangul_jamo_to_syllable",
]
CONSTS = ["syllable_base", "choseong_base", "jungseong_base", "jongseong_base",
          "njungseong", "njongseong"]

lines = SRC.read_text(encoding="utf-8").splitlines()


def slice_func(name):
    i = next(k for k, l in enumerate(lines) if l.startswith(name + "("))
    j = i - 1
    while j >= 0 and re.fullmatch(r"(static\s+)?[\w\s\*]+", lines[j]) and lines[j].strip():
        j -= 1
    j += 1
    k = i
    while lines[k] != "}":
        k += 1
    body = lines[j:k + 1]
    if body[0].startswith("static "):
        body[0] = body[0][len("static "):]
    sig = " ".join(l.strip() for l in body[: body.index(next(x for x in body if x == "{"))])
    return "\n".join(body), sig


def rename(s):
    return re.sub(r"\bhangul_", "hm_", s)


out_c = ["""/* GENERATED by tools/extract_tables.py -- DO NOT EDIT.
 * Source: data-orig/libhangul/hangulctype.c (libhangul 0.2.0, LGPL-2.1+,
 * (c) Choe Hwanjin and libhangul contributors). Renamed hangul_* -> hm_*.
 */
#include "tables.h"
#include <stdbool.h>
#include <stdint.h>
"""]
out_h = ["""/* GENERATED by tools/extract_tables.py -- DO NOT EDIT (see tables.c header). */
#ifndef HUNMIN_TABLES_H
#define HUNMIN_TABLES_H
#include <stdbool.h>
#include <stdint.h>
typedef uint32_t ucschar;
#define N_ELEMENTS(a) (sizeof(a) / sizeof((a)[0]))
#ifndef countof
#define countof(a) N_ELEMENTS(a)
#endif
"""]

for c in CONSTS:
    for l in lines:
        if re.match(rf"static const \w+ {c}\s*=", l):
            out_c.append(rename(l))
            break

for f in FUNCS:
    body, sig = slice_func(f)
    out_h.append(rename(sig) + ";")
    out_c.append(rename(body))

out_h.append("#endif")
(OUT / "tables.c").write_text("\n".join(out_c) + "\n", encoding="utf-8")
(OUT / "tables.h").write_text("\n".join(out_h) + "\n", encoding="utf-8")
print(f"wrote {OUT/'tables.c'} and tables.h ({len(FUNCS)} functions)")
