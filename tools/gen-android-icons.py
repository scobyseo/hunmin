#!/usr/bin/env python3
"""gen-android-icons.py — Android launcher icons derived from the Windows one.

Source of truth: `frontends/tsf/assets/hunmin-256.png`, the 256-px preview of
the same 512-px render `hunmin.ico` stores. The Windows TIP serves that .ico
from its own resources, so the two frontends showing different marks was an
omission, not a design.

Provenance (recorded here because this tool is what produces the files):

- The artwork is the King Sejong illustration from 어반브러시 / Urbanbrush,
  retrieved 2026-10-18; the licence term taken from the site's own terms page
  requires the credit "출처: 어반브러시" for online use, which
  `frontends/tsf/assets/README.md` and `debian/copyright` carry. The same
  term applies to these derived icons: they are the same illustration.
- What was excluded: the source illustration's mugunghwa flowers and watermark
  badge, exactly as that README records for the .ico.
- What this tool does NOT represent: it draws nothing new. It downsamples one
  existing render into the Android launcher shapes — a legacy square mipmap
  (the badge with its own transparent corners) and an adaptive-icon foreground
  inset to the 108dp safe zone over a solid background.

Run: python3 tools/gen-android-icons.py [--check]
`--check` regenerates into a temp dir and reports whether the tree is current.
"""

from __future__ import annotations

import argparse
import pathlib
import sys

from PIL import Image
try:  # issue #272 phase 2: one ROOT derivation, with a file-relative fallback
    from _common import ROOT as _COMMON_ROOT
except ImportError:  # run from outside tools/: derive from this file
    _COMMON_ROOT = __import__("pathlib").Path(__file__).resolve().parent.parent

REPO = _COMMON_ROOT
SOURCE = REPO / "frontends/tsf/assets/hunmin-256.png"
RES = REPO / "frontends/android/app/src/main/res"

# Legacy mipmaps: the badge at the launcher's own density size.
LEGACY = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}

# Adaptive-icon foreground canvases: 108dp at each density.
ADAPTIVE = {"mdpi": 108, "hdpi": 162, "xhdpi": 216, "xxhdpi": 324, "xxxhdpi": 432}

# The badge inside the 108dp canvas. 66/108 keeps the golden ring inside the
# mask on a circular-mask launcher (a badge at the full 72dp safe zone has its
# ring cut in half by that mask) and still reads as a launcher icon on a
# squircle.
FOREGROUND_BADGE_FRACTION = 66 / 108

BACKGROUND = "#FFFFFF"  # the ring's own interior: the badge reads as drawn

ADAPTIVE_XML = """<?xml version="1.0" encoding="utf-8"?>
<!-- SPDX-License-Identifier: LGPL-2.1-or-later
     Generated by tools/gen-android-icons.py from frontends/tsf/assets/hunmin-256.png;
     the provenance and the licence term live in that script's docstring. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
</adaptive-icon>
"""

COLOR_XML = """<?xml version="1.0" encoding="utf-8"?>
<!-- SPDX-License-Identifier: LGPL-2.1-or-later
     Generated by tools/gen-android-icons.py: the badge's own interior colour. -->
<resources>
    <color name="ic_launcher_background">{colour}</color>
</resources>
"""


def load_source() -> Image.Image:
    if not SOURCE.exists():
        sys.exit(f"missing source render: {SOURCE}")
    return Image.open(SOURCE).convert("RGBA")


def render_legacy(src: Image.Image, size: int) -> Image.Image:
    return src.resize((size, size), Image.Resampling.LANCZOS)


def render_foreground(src: Image.Image, canvas: int) -> Image.Image:
    badge = round(canvas * FOREGROUND_BADGE_FRACTION)
    out = Image.new("RGBA", (canvas, canvas), (0, 0, 0, 0))
    art = src.resize((badge, badge), Image.Resampling.LANCZOS)
    off = (canvas - badge) // 2
    out.paste(art, (off, off), art)
    return out


def plan() -> dict[pathlib.Path, bytes]:
    """Every file this tool owns, as path -> bytes (PNG or UTF-8 XML)."""
    import io

    src = load_source()
    files: dict[pathlib.Path, bytes] = {}

    # WebP, not PNG: the artwork is photographic, and the same render as PNG
    # cost 308 KB across these densities - 14% of the whole APK for a launcher
    # icon. Lossy WebP at quality 90 is visually identical at icon sizes and
    # the format is supported from API 14 (this app's floor is 24).
    for density, size in LEGACY.items():
        buf = io.BytesIO()
        render_legacy(src, size).save(buf, format="WEBP", quality=90, method=6)
        files[RES / f"mipmap-{density}/ic_launcher.webp"] = buf.getvalue()

    for density, canvas in ADAPTIVE.items():
        buf = io.BytesIO()
        render_foreground(src, canvas).save(buf, format="WEBP", quality=90, method=6)
        files[RES / f"mipmap-{density}/ic_launcher_foreground.webp"] = buf.getvalue()

    # ONE adaptive XML: the badge is circular, so android:roundIcon points at
    # this same resource rather than at a duplicate bitmap.
    files[RES / "mipmap-anydpi-v26/ic_launcher.xml"] = ADAPTIVE_XML.encode()
    files[RES / "values/ic_launcher_background.xml"] = COLOR_XML.format(colour=BACKGROUND).encode()
    return files


# Files this tool used to write and no longer does. Removed on a normal run so
# a regenerated tree carries the shapes it ships, not a history of them.
OBSOLETE = [
    *[RES / f"mipmap-{d}/ic_launcher.png" for d in LEGACY],
    *[RES / f"mipmap-{d}/ic_launcher_round.png" for d in LEGACY],
    *[RES / f"mipmap-{d}/ic_launcher_foreground.png" for d in ADAPTIVE],
    RES / "mipmap-anydpi-v26/ic_launcher_round.xml",
]


def main() -> int:
    ap = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    ap.add_argument("--check", action="store_true", help="report staleness, write nothing")
    args = ap.parse_args()

    stale: list[pathlib.Path] = []
    for path, data in plan().items():
        if args.check:
            if not path.exists() or path.read_bytes() != data:
                stale.append(path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)

    if not args.check:
        for path in OBSOLETE:
            if path.exists():
                path.unlink()
                print(f"removed: {path.relative_to(REPO)}")

    if args.check:
        if stale:
            for p in stale:
                print(f"stale: {p.relative_to(REPO)}")
            return 1
        print(f"android icons: current ({len(plan())} files)")
        return 0

    print(f"wrote {len(plan())} icon files under {RES.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())