"""Type a real text through one layout and record the engine's answer (tier A).

The corpus needs prose, not only syllables. This tool takes a UTF-8 text file
(one line per line, '#' comments are provenance and are never typed) and writes
a tier-A golden whose expectations are `hunmin-sim --trace`'s own output over
keys that were SEARCHED, not typed:

  * the keys come from tools/sin3p2-ksgen.py (BFS over the layout's own key
    table, hunmin-sim --batch as the oracle), so a layout with no static
    jamo->key table (sin3-p2) is handled the same way as one that has;
  * every line is then re-typed WHOLE, because a syllable's keystroke found from
    an empty buffer can compose differently in the middle of a line
    (`mfc` → 학 alone, but ㅌ학 inside a word). A line that does not render its
    own text is recorded as `excluded` with what it rendered instead, and is
    NOT emitted: a corpus that quietly drops a line looks like it covers the
    text.

The golden carries the case per LINE, so a reader can see which line broke, and
tier A replays each line from a clean engine (docs/SPEC-SCHEMA.md).

Hanja is KEPT in the text. No layout emits it, so a run of ideographs is recorded
as a `hanja_segments` entry on that case instead of being dropped: the events
still say exactly what the engine composes, and an environment that can enter
hanja (the hanja conversion surface) can evaluate the whole line. A character
that is neither typeable nor hanja -- CJK punctuation, an emoji -- still excludes
the line, because no frontend can deliver it either.

    python3 tools/gen-cultural-golden.py --text-file tests/golden/texts/seosi.txt \\
        --layout dubeolsik --out tests/golden/cultural-seosi-dubeolsik.jsonl

Why this exists: the four `ref-*-seosi/anthem*.jsonl` files that predate it were
written by a `gen-cultural-golden` that never reached the tree, and what they
actually render is not the poem (measured: ref-dubeolsik-seosi renders
주닝날록사라어울). An artefact without retrievable provenance is not evidence,
so the replacement is generated by a committed tool.
"""
import argparse
import json
import pathlib
import subprocess
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_SIM = REPO / "build" / "hunmin-sim"
DEFAULT_DATA = REPO / "libhunmin" / "data"


def sim(a, layout, keys, mode="--batch"):
    argv = [str(a.sim), "--data", str(a.data), "--layout", layout]
    if mode == "--batch":
        argv.append("--batch")
        r = subprocess.run(argv, input=keys + "\n", capture_output=True,
                           encoding="utf-8", errors="replace", timeout=600)
        if r.returncode != 0:
            raise SystemExit(f"hunmin-sim --batch failed: {r.stderr.strip()[:300]}")
        return json.loads(r.stdout)
    r = subprocess.run(argv + ["--keys", keys, "--trace"], capture_output=True,
                       encoding="utf-8", errors="replace", timeout=600)
    if r.returncode != 0:
        raise SystemExit(f"hunmin-sim --trace failed: {r.stderr.strip()[:300]}")
    return [json.loads(l) for l in r.stdout.splitlines() if l.startswith("{")]


def sim_many(a, layout, keys_list):
    """Rendered text for many keystroke strings, in ONE engine process."""
    if not keys_list:
        return []
    argv = [str(a.sim), "--data", str(a.data), "--layout", layout, "--batch"]
    r = subprocess.run(argv, input="\n".join(keys_list) + "\n", capture_output=True,
                       encoding="utf-8", errors="replace", timeout=600)
    if r.returncode != 0:
        raise SystemExit(f"hunmin-sim --batch failed: {r.stderr.strip()[:300]}")
    return [rendered(json.loads(l)) for l in r.stdout.splitlines() if l.startswith("{")]


def rendered(rec):
    return rec["commit"] + rec["preedit"]


def read_lines(path):
    """[(line number, text)] for the lines that are typed. Blank lines are
    stanza breaks: they are structure, not input, so they are not returned."""
    out = []
    for n, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if raw.startswith("#") or not raw.strip():
            continue
        out.append((n, raw))
    if not out:
        raise SystemExit(f"{path}: no typable lines")
    return out


def syllable_keys(a, layout, text):
    """Per-character keystrokes for every character the text uses, from the
    search tool -- the tool that owns the layout automaton.

    The search is a BFS over the layout's automaton and costs minutes for a
    whole text on sin3-p2, so its JSON can be reused (`--ksgen`) while iterating
    on the assembly below; the committed artefact still comes from a run that
    searched, and the golden's meta names the tool either way.
    """
    if a.ksgen:
        return json.loads(a.ksgen.read_text(encoding="utf-8"))["keystrokes"]
    tmp = pathlib.Path(a.work) / "targets.txt"
    tmp.write_text("".join(sorted({c for _, line in text for c in line if c != " "})),
                   encoding="utf-8")
    out = pathlib.Path(a.work) / "ksgen.json"
    r = subprocess.run([sys.executable, str(REPO / "tools/sin3p2-ksgen.py"),
                        "--layout", layout, "--text-file", str(tmp),
                        "--out", str(out)], capture_output=True, text=True)
    if r.returncode != 0:
        raise SystemExit(f"sin3p2-ksgen failed: {r.stderr.strip()[:400]}")
    return json.loads(out.read_text(encoding="utf-8"))["keystrokes"]


HANJA_BECAUSE = ("no layout emits hanja: a frontend delivers it through hanja "
                 "conversion (docs/SPEC-MODES.md), so this run has no key events and "
                 "no tier-A expectation -- an environment that can enter hanja "
                 "evaluates it, a key-event replay cannot")


def is_hanja(c):
    """CJK ideographs, the set a hanja conversion can deliver."""
    o = ord(c)
    return (0x4E00 <= o <= 0x9FFF or 0x3400 <= o <= 0x4DBF
            or 0xF900 <= o <= 0xFAFF or 0x20000 <= o <= 0x2FA1F)


CHO = ["ㄱ", "ㄲ", "ㄴ", "ㄷ", "ㄸ", "ㄹ", "ㅁ", "ㅂ", "ㅃ", "ㅅ", "ㅆ", "ㅇ",
       "ㅈ", "ㅉ", "ㅊ", "ㅋ", "ㅌ", "ㅍ", "ㅎ"]
JUNG = ["ㅏ", "ㅐ", "ㅑ", "ㅒ", "ㅓ", "ㅔ", "ㅕ", "ㅖ", "ㅗ", "ㅘ", "ㅙ", "ㅚ", "ㅛ",
        "ㅜ", "ㅝ", "ㅞ", "ㅟ", "ㅠ", "ㅡ", "ㅢ", "ㅣ"]
JONG = ["", "ㄱ", "ㄲ", "ㄳ", "ㄴ", "ㄵ", "ㄶ", "ㄷ", "ㄹ", "ㄺ", "ㄻ", "ㄼ", "ㄽ",
        "ㄾ", "ㄿ", "ㅀ", "ㅁ", "ㅂ", "ㅄ", "ㅅ", "ㅆ", "ㅇ", "ㅈ", "ㅊ", "ㅋ",
        "ㅌ", "ㅍ", "ㅎ"]


def hangul_keys_from_table(syl, table):
    """cho -> jung -> jong keystrokes for one syllable, from a jamo table.

    A BFS (tools/sin3p2-ksgen.py) is the tool for an automaton whose keys mean
    different things by state, but it explodes with depth: measured on this text
    it found 81 of 124 targets and could not reach `없` or `워` at depth 4. A
    세벌식 layout puts cho, jung and jong on separate keys, so the keystroke is a
    lookup once the slot is known (tools/jamo-keytable.py probes that table and
    is what this reads).
    """
    x = ord(syl) - 0xAC00
    cho, jung, jong = CHO[x // 588], JUNG[(x % 588) // 28], JONG[x % 28]
    keys = ""
    for slot, jamo in (("cho", cho), ("jung", jung), ("jong", jong)):
        if not jamo:
            continue
        k = table.get(slot, {}).get(jamo)
        if not k:
            return None
        keys += k
    return keys


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--text-file", type=pathlib.Path, required=True)
    ap.add_argument("--layout", required=True)
    ap.add_argument("--out", type=pathlib.Path, required=True)
    ap.add_argument("--sim", type=pathlib.Path, default=DEFAULT_SIM)
    ap.add_argument("--data", type=pathlib.Path, default=DEFAULT_DATA)
    ap.add_argument("--work", type=pathlib.Path, default=None,
                    help="scratch dir for the search tool's intermediate JSON")
    ap.add_argument("--ksgen", type=pathlib.Path, default=None,
                    help="reuse this sin3p2-ksgen JSON instead of searching")
    ap.add_argument("--jamo-table", type=pathlib.Path, default=None,
                    help="use this tools/jamo-keytable.py JSON instead of a BFS "
                         "(the 세벌식 layouts: cho/jung/jong sit on separate keys)")
    a = ap.parse_args()
    if a.work is None:
        import tempfile
        a.work = tempfile.mkdtemp(prefix="hunmin-cultural-")
    else:
        a.work.mkdir(parents=True, exist_ok=True)

    lines = read_lines(a.text_file)
    jamo_table = None
    if a.jamo_table:
        jamo_table = json.loads(a.jamo_table.read_text(encoding="utf-8"))["table"]
    keys_of = {} if jamo_table else syllable_keys(a, a.layout, lines)

    # Which single key event emits each ASCII character? MEASURED over the
    # layout's own keys, both plain and shifted -- never read off the table,
    # because a 세벌식 table's values are nested `case` trees whose branch
    # depends on state: sin3-p2 emits `'` on the SHIFT of `j` and `/` on the
    # SHIFT of `'`, which no flat `=x` lookup can see (measured: `J` -> `'`,
    # `"` -> `/`, while the bare `'` position is ᄐ).
    keys_of_layout = list(json.loads((pathlib.Path(a.data) / "layouts" / f"{a.layout}.json").read_text(encoding="utf-8"))["keys"])
    ascii_chars = sorted({c for _, line in lines for c in line
                          if 0x20 <= ord(c) <= 0x7E and c != " "})
    probes, owner = [], []
    for c in ascii_chars:
        for cand in [c] + ["\\s" + k for k in keys_of_layout]:
            probes.append(cand)
            owner.append(c)
    rendered_all = sim_many(a, a.layout, probes)
    ascii_key = {}
    for c in ascii_chars:
        hits = [cand for cand, ch, r in zip(probes, owner, rendered_all)
                if ch == c and r == c]
        if hits:
            ascii_key[c] = hits[0]                    # the layout spells it
        elif rendered_all[probes.index(c)] == "":
            ascii_key[c] = None                       # no such key: client inserts it
        else:
            ascii_key[c] = False                      # untypeable on this layout

    def engine_keys(c):
        """The keystroke that composes a Hangul syllable, or None.

        ASCII never comes through here: whether the layout spells a symbol is
        answered by probing the key alone (above), because a table cannot say
        what a shifted position emits on a layout whose shift row is jamo.
        """
        if 0xAC00 <= ord(c) <= 0xD7A3:
            if jamo_table:
                return hangul_keys_from_table(c, jamo_table)
            return keys_of.get(c)
        return None

    cases, excluded = [], []
    for n, line in lines:
        # One unit per character: what key produces it, whether the ENGINE
        # composes it (as opposed to the client inserting it), and whether its
        # keystroke may need its leading signal keys dropped.
        units, missing = [], []
        for c in line:
            if c == " ":
                units.append({"ch": c, "keys": " ", "engine": False, "hanja": False})
                continue
            if is_hanja(c):
                units.append({"ch": c, "keys": None, "engine": False, "hanja": True})
                continue
            if 0xAC00 <= ord(c) <= 0xD7A3:
                ek = engine_keys(c)
                if ek is None:
                    missing.append(f"{c} (no keystroke composes it)")
                    continue
                units.append({"ch": c, "keys": ek, "engine": True, "hanja": False})
                continue
            if 0x20 <= ord(c) <= 0x7E:
                if c in keys_of:          # a key the search found (searched layouts)
                    units.append({"ch": c, "keys": keys_of[c], "engine": True, "hanja": False})
                    continue
                key = ascii_key.get(c)
                if key:                   # the layout spells it (measured, incl. shift)
                    units.append({"ch": c, "keys": key, "engine": True, "hanja": False})
                elif key is None:         # no such key: the client inserts the character
                    units.append({"ch": c, "keys": c, "engine": False, "hanja": False})
                else:
                    missing.append(f"{c} (no key event emits it on {a.layout})")
                continue
            missing.append(c)
        if missing:
            excluded.append({"line": n, "text": line,
                             "because": f"no key and no frontend path for "
                                        f"{''.join(sorted(set(missing)))}"})
            continue

        want = "".join(u["ch"] for u in units if u["engine"])

        # Signal keys (`\`` and `'`) exist to reach a CHO from an EMPTY buffer.
        # Inside a line the previous syllable leaves the state ready, and the
        # same key then types a stray jamo -- measured on sin3-p2, where the
        # plain concatenation renders none of the poem's lines. So assemble the
        # line with the leading signals kept or dropped, and let the ENGINE pick
        # the variant that composes: at most 2^k candidates, k = the number of
        # syllables whose keystroke actually starts with a signal key.
        # Signal stripping is a property of the BFS alphabet (`'`/`` ` `` reach a
        # CHO from an empty buffer). A jamo table has no such prefix, and a
        # layout that spells a literal apostrophe on the `'` position must not
        # have it stripped, so the table mode keeps the assembly verbatim.
        sig = [] if jamo_table else [i for i, u in enumerate(units)
                                     if u["engine"] and u["keys"][:1] in ("`", "'")
                                     and len(u["keys"]) > 1]

        def assemble(mask: int) -> str:
            out = ""
            for i, u in enumerate(units):
                if u["keys"] is None:      # hanja: no key event exists
                    continue
                k = u["keys"]
                if i in sig and (mask >> sig.index(i)) & 1:
                    k = k.lstrip("`'")
                out += k
            return out

        tried = [assemble(m) for m in range(1 << len(sig))]
        renders = sim_many(a, a.layout, tried)
        picked = next(((m, k) for m, k in enumerate(tried) if renders[m] == want), None)
        if picked is None:
            excluded.append({"line": n, "text": line,
                             "because": f"renders {renders[0]!r} with the signals kept "
                                        f"and {renders[-1]!r} without them"})
            continue
        mask, keys = picked

        segments, run = [], {"kind": None, "text": ""}

        def close_run():
            if not run["text"]:
                return
            if run["kind"] == "engine":
                segments.append({"engine": run["text"]})
            else:
                segments.append({"hanja": run["text"], "because": HANJA_BECAUSE})
            run["kind"], run["text"] = None, ""

        for u in units:
            kind = "hanja" if u["hanja"] else "engine"
            if run["kind"] != kind:
                close_run()
                run["kind"] = kind
            run["text"] += u["ch"]
        close_run()

        cases.append((f"line-{n:02d}", line, keys, mask,
                      [s for s in segments if "hanja" in s]))

    if not cases:
        raise SystemExit("not one line composed; nothing to write")

    meta = {
        "layout": a.layout,
        "text": a.text_file.name,
        "tool": "tools/gen-cultural-golden.py",
        "method": "keys per character from tools/sin3p2-ksgen.py (BFS over the "
                  "layout's own key table, hunmin-sim --batch oracle); a character "
                  "with no keystroke is read from the layout's literal keys; each "
                  "line is re-typed whole and kept only if the engine composes its "
                  "characters; expectations are hunmin-sim --trace output, never typed",
        "not_in_the_events": "the boundary (space) and literal (punctuation) keys: the "
                            "engine declines them, so the client inserts the character "
                            "and the trace records consumed=false for that event",
        "assembly": "a syllable's keystroke found from an empty buffer carries "
                    "leading signal keys that type a stray jamo mid-line, so each "
                    "line is assembled with those signals kept or dropped and the "
                    "ENGINE picks the variant that composes",
        "cases": f"{len(cases)} of {len(lines)} lines",
    }
    if excluded:
        meta["excluded"] = excluded

    out = [json.dumps({"meta": meta}, ensure_ascii=False)]
    for label, line, keys, mask, hanja_runs in cases:
        case_meta = {"case": label, "text": line, "keys": keys}
        if mask:
            case_meta["signals_dropped"] = True
        if hanja_runs:
            case_meta["hanja_segments"] = hanja_runs
        out.append(json.dumps({"meta": case_meta}, ensure_ascii=False))
        for rec in sim(a, a.layout, keys, mode="--trace"):
            out.append(json.dumps({"in": rec["in"], "commit": rec.get("commit", ""),
                                   "preedit": rec.get("preedit", "")},
                                  ensure_ascii=False))
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text("\n".join(out) + "\n", encoding="utf-8")

    events = sum(1 for l in out if '"in"' in l)
    print(f"{a.out}: {len(cases)}/{len(lines)} lines, {events} events", file=sys.stderr)
    for e in excluded:
        print(f"  excluded line {e['line']}: {e['because']}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())