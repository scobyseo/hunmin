"""Type a real text through one layout and record the engine's answer (tier A).

The corpus needs prose, not only syllables. This tool takes a UTF-8 text file
(one line per line, '#' comments are provenance and are never typed) and writes
a tier-A golden whose expectations are `hunmin-sim --trace`'s own output over
keys that were SEARCHED, not typed:

  * the keys come from tools/sin3p2-ksgen.py (BFS over the layout's own key
    table, hunmin-sim --batch as the oracle), so a layout with no static
    jamo->key table (sin3-p2) is handled the same way as one that has;
  * every line is then re-typed WHOLE, because a syllable's keystroke found from
    an empty buffer can compose differently in the middle of a line
    (`mfc` → 학 alone, but ㅌ학 inside a word). A line that does not render its
    own text is recorded as `excluded` with what it rendered instead, and is
    NOT emitted: a corpus that quietly drops a line looks like it covers the
    text.

The golden carries the case per LINE, so a reader can see which line broke, and
tier A replays each line from a clean engine (docs/SPEC-SCHEMA.md).

Hanja is KEPT in the text. No layout emits it, so a run of ideographs is recorded
as a `hanja_segments` entry on that case instead of being dropped: the events
still say exactly what the engine composes, and an environment that can enter
hanja (the hanja conversion surface) can evaluate the whole line. A character
that is neither typeable nor hanja -- CJK punctuation, an emoji -- still excludes
the line, because no frontend can deliver it either.

    python3 tools/gen-cultural-golden.py --text-file tests/golden/texts/seosi.txt \\
        --layout dubeolsik --out tests/golden/cultural-seosi-dubeolsik.jsonl

Why this exists: the four `ref-*-seosi/anthem*.jsonl` files that predate it were
written by a `gen-cultural-golden` that never reached the tree, and what they
actually render is not the poem (measured: ref-dubeolsik-seosi renders
주닝날록사라어울). An artefact without retrievable provenance is not evidence,
so the replacement is generated by a committed tool.
"""
import argparse
import json
import pathlib
import subprocess
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_SIM = REPO / "build" / "hunmin-sim"
DEFAULT_DATA = REPO / "libhunmin" / "data"


def sim(a, layout, keys, mode="--batch"):
    argv = [str(a.sim), "--data", str(a.data), "--layout", layout]
    if mode == "--batch":
        argv.append("--batch")
        r = subprocess.run(argv, input=keys + "\n", capture_output=True,
                           encoding="utf-8", errors="replace", timeout=600)
        if r.returncode != 0:
            raise SystemExit(f"hunmin-sim --batch failed: {r.stderr.strip()[:300]}")
        return json.loads(r.stdout)
    r = subprocess.run(argv + ["--keys", keys, "--trace"], capture_output=True,
                       encoding="utf-8", errors="replace", timeout=600)
    if r.returncode != 0:
        raise SystemExit(f"hunmin-sim --trace failed: {r.stderr.strip()[:300]}")
    return [json.loads(l) for l in r.stdout.splitlines() if l.startswith("{")]


def rendered(rec):
    return rec["commit"] + rec["preedit"]


def read_lines(path):
    """[(line number, text)] for the lines that are typed. Blank lines are
    stanza breaks: they are structure, not input, so they are not returned."""
    out = []
    for n, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if raw.startswith("#") or not raw.strip():
            continue
        out.append((n, raw))
    if not out:
        raise SystemExit(f"{path}: no typable lines")
    return out


def syllable_keys(a, layout, text):
    """Per-character keystrokes for every character the text uses, from the
    search tool -- the tool that owns the layout automaton."""
    tmp = pathlib.Path(a.work) / "targets.txt"
    tmp.write_text("".join(sorted({c for _, line in text for c in line if c != " "})),
                   encoding="utf-8")
    out = pathlib.Path(a.work) / "ksgen.json"
    r = subprocess.run([sys.executable, str(REPO / "tools/sin3p2-ksgen.py"),
                        "--layout", layout, "--text-file", str(tmp),
                        "--out", str(out)], capture_output=True, text=True)
    if r.returncode != 0:
        raise SystemExit(f"sin3p2-ksgen failed: {r.stderr.strip()[:400]}")
    return json.loads(out.read_text(encoding="utf-8"))["keystrokes"]


HANJA_BECAUSE = ("no layout emits hanja: a frontend delivers it through hanja "
                 "conversion (docs/SPEC-MODES.md), so this run has no key events and "
                 "no tier-A expectation -- an environment that can enter hanja "
                 "evaluates it, a key-event replay cannot")


def is_hanja(c):
    """CJK ideographs, the set a hanja conversion can deliver."""
    o = ord(c)
    return (0x4E00 <= o <= 0x9FFF or 0x3400 <= o <= 0x4DBF
            or 0xF900 <= o <= 0xFAFF or 0x20000 <= o <= 0x2FA1F)


def literal_keys(layout, data):
    """char -> keystroke for the layout's LITERAL keys (`=x` in the table).

    Punctuation never reaches the engine: the adapter declines the key and the
    client inserts the character, so `hunmin-sim` renders nothing for it and the
    BFS below can never "find" it. The layout table states which character each
    key emits, so the mapping is read, not guessed. A shifted literal is the
    uppercase key, the same convention every other key string uses.
    """
    d = json.loads((pathlib.Path(data) / "layouts" / f"{layout}.json").read_text(encoding="utf-8"))
    out = {}
    for key, forms in d["keys"].items():
        for form, shift in (("plain", False), ("shift", True)):
            v = forms.get(form)
            if isinstance(v, str) and v.startswith("=") and len(v) == 2:
                ch = v[1]
                out.setdefault(ch, key.upper() if shift else key)
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--text-file", type=pathlib.Path, required=True)
    ap.add_argument("--layout", required=True)
    ap.add_argument("--out", type=pathlib.Path, required=True)
    ap.add_argument("--sim", type=pathlib.Path, default=DEFAULT_SIM)
    ap.add_argument("--data", type=pathlib.Path, default=DEFAULT_DATA)
    ap.add_argument("--work", type=pathlib.Path, default=None,
                    help="scratch dir for the search tool's intermediate JSON")
    a = ap.parse_args()
    if a.work is None:
        import tempfile
        a.work = tempfile.mkdtemp(prefix="hunmin-cultural-")
    else:
        a.work.mkdir(parents=True, exist_ok=True)

    lines = read_lines(a.text_file)
    keys_of = syllable_keys(a, a.layout, lines)
    literals = literal_keys(a.layout, a.data)

    cases, excluded = [], []
    for n, line in lines:
        typed, pass_through, missing, engine_expect = [], [], [], []
        segments = []          # ordered runs: {"engine": text} / {"hanja": text, ...}
        run = {"kind": None, "text": ""}

        def close_run():
            if not run["text"]:
                return
            if run["kind"] == "engine":
                segments.append({"engine": run["text"]})
            else:
                segments.append({"hanja": run["text"], "because": HANJA_BECAUSE})
            run["kind"], run["text"] = None, ""

        for c in line:
            if c == " " or c in keys_of or c in literals or 0x20 <= ord(c) <= 0x7E:
                if run["kind"] != "engine":
                    close_run()
                    run["kind"] = "engine"
                run["text"] += c
                if c == " ":
                    typed.append(" ")          # the boundary key, forwarded to the client
                    pass_through.append(" ")
                elif c in keys_of:
                    typed.append(keys_of[c])
                    engine_expect.append(c)
                elif c in literals:
                    typed.append(literals[c])  # a literal key: the client inserts it
                    pass_through.append(c)
                else:
                    # Printable ASCII the layout does not map (no shipped layout
                    # table carries punctuation at all: dubeolsik's is 26
                    # letters). The adapter declines the key and the client
                    # inserts the character, so it is a real event with no
                    # engine output.
                    typed.append(c)
                    pass_through.append(c)
            elif is_hanja(c):
                # Hanja has NO key on any layout: a frontend delivers it through
                # hanja conversion (docs/SPEC-MODES.md), which is a frontend
                # surface, not an engine one. The line is kept and the run is
                # recorded as a `hanja` segment, so an environment that CAN enter
                # hanja evaluates the full text while the events still describe
                # exactly what the engine composes.
                if run["kind"] != "hanja":
                    close_run()
                    run["kind"] = "hanja"
                run["text"] += c
            else:
                missing.append(c)
        close_run()
        if missing:
            excluded.append({"line": n, "text": line,
                             "because": f"no key and no frontend path for "
                                        f"{''.join(sorted(set(missing)))}"})
            continue
        keys = "".join(typed)
        got = rendered(sim(a, a.layout, keys))
        # Boundary and literal keys are declined by the engine and inserted by
        # the client, so the engine's commit stream never carries them
        # (docs/trace-spec.md `consumed`). Compare the characters the ENGINE
        # composes, and record the rest in the meta rather than letting a reader
        # think the corpus dropped them.
        want = "".join(engine_expect)
        if got != want:
            excluded.append({"line": n, "text": line,
                             "because": f"the concatenation renders {got!r}"})
            continue
        cases.append((f"line-{n:02d}", line, keys,
                      [s for s in segments if "hanja" in s]))

    if not cases:
        raise SystemExit("not one line composed; nothing to write")

    meta = {
        "layout": a.layout,
        "text": a.text_file.name,
        "tool": "tools/gen-cultural-golden.py",
        "method": "keys per character from tools/sin3p2-ksgen.py (BFS over the "
                  "layout's own key table, hunmin-sim --batch oracle); a character "
                  "with no keystroke is read from the layout's literal keys; each "
                  "line is re-typed whole and kept only if the engine composes its "
                  "characters; expectations are hunmin-sim --trace output, never typed",
        "not_in_the_events": "the boundary (space) and literal (punctuation) keys: the "
                            "engine declines them, so the client inserts the character "
                            "and the trace records consumed=false for that event",
        "cases": f"{len(cases)} of {len(lines)} lines",
    }
    if excluded:
        meta["excluded"] = excluded

    out = [json.dumps({"meta": meta}, ensure_ascii=False)]
    for label, line, keys, hanja_runs in cases:
        case_meta = {"case": label, "text": line, "keys": keys}
        if hanja_runs:
            case_meta["hanja_segments"] = hanja_runs
        out.append(json.dumps({"meta": case_meta}, ensure_ascii=False))
        for rec in sim(a, a.layout, keys, mode="--trace"):
            out.append(json.dumps({"in": rec["in"], "commit": rec.get("commit", ""),
                                   "preedit": rec.get("preedit", "")},
                                  ensure_ascii=False))
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text("\n".join(out) + "\n", encoding="utf-8")

    events = sum(1 for l in out if '"in"' in l)
    print(f"{a.out}: {len(cases)}/{len(lines)} lines, {events} events", file=sys.stderr)
    for e in excluded:
        print(f"  excluded line {e['line']}: {e['because']}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())